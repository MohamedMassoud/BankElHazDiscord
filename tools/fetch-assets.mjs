// Build-time helper: downloads each board tile's Wikipedia thumbnail once and
// writes a title -> local-path map. Run: node tools/fetch-assets.mjs
// (Requires network at build time only; the game itself never calls out.)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const HTML = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');

const m = HTML.match(/const WT0=(\{[\s\S]*?\});/);
if (!m) { console.error('could not find WT0 in index.html'); process.exit(1); }
const WT0 = eval('(' + m[1] + ')');

const OUT = path.join(ROOT, 'assets', 'img');
fs.mkdirSync(OUT, { recursive: true });

const slug = (t) => String(t).replace(/[^A-Za-z0-9]+/g, '_').replace(/^_+|_+$/g, '') || 'img';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function summary(title) {
  const url = 'https://en.wikipedia.org/api/rest_v1/page/summary/' + encodeURIComponent(title);
  const r = await fetch(url, { headers: { 'user-agent': 'BankElHaz/1.0 (asset fetch)' } });
  if (!r.ok) return null;
  return r.json();
}

const map = {};
const titles = [...new Set(Object.values(WT0))];
let ok = 0, fail = 0;
for (const title of titles) {
  try {
    const j = await summary(title);
    const src = (j && j.thumbnail && j.thumbnail.source) || (j && j.originalimage && j.originalimage.source) || null;
    if (!src) { console.log('MISS', title); fail++; continue; }
    const ext = (src.split('?')[0].match(/\.(jpg|jpeg|png|webp|gif)$/i) || [,'jpg'])[1].toLowerCase();
    const file = slug(title) + '.' + ext;
    const ir = await fetch(src, { headers: { 'user-agent': 'BankElHaz/1.0 (asset fetch)' } });
    if (!ir.ok) { console.log('DLFAIL', title, ir.status); fail++; continue; }
    fs.writeFileSync(path.join(OUT, file), Buffer.from(await ir.arrayBuffer()));
    map[title] = 'assets/img/' + file;
    ok++;
    console.log('OK', title, '->', file);
  } catch (e) {
    console.log('ERR', title, e.message); fail++;
  }
  await sleep(120);
}

const js = '/* auto-generated by tools/fetch-assets.mjs — local tile thumbnails */\n' +
  'window.__IMG_LOCAL=' + JSON.stringify(map, null, 0) + ';\n';
fs.writeFileSync(path.join(ROOT, 'assets', 'img-map.js'), js);
console.log(`\nDONE ok=${ok} fail=${fail} total=${titles.length}`);
console.log('wrote assets/img-map.js');
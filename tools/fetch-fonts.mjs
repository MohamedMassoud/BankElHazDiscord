// Build-time helper: downloads Cairo + Amiri woff2 files and rewrites the CSS
// to local paths. Run: node tools/fetch-fonts.mjs
// The game then loads assets/fonts.css (no fonts.googleapis.com calls).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', 'public');
const OUT = path.join(ROOT, 'assets', 'fonts');
fs.mkdirSync(OUT, { recursive: true });

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const url = 'https://fonts.googleapis.com/css2?family=Cairo:wght@400..900&family=Amiri:wght@400;700&display=swap';

const css = await (await fetch(url, { headers: { 'user-agent': UA } })).text();

const seen = new Map();
const localCss = css.replace(/url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/g, (full, u) => {
  const base = u.split('/').pop();
  if (!seen.has(base)) seen.set(base, u);
  return `url(fonts/${base})`;
});

let ok = 0, fail = 0;
for (const [base, u] of seen) {
  try {
    const r = await fetch(u, { headers: { 'user-agent': UA } });
    if (!r.ok) { console.log('DLFAIL', base, r.status); fail++; continue; }
    fs.writeFileSync(path.join(OUT, base), Buffer.from(await r.arrayBuffer()));
    ok++;
  } catch (e) { console.log('ERR', base, e.message); fail++; }
}

fs.writeFileSync(path.join(ROOT, 'assets', 'fonts.css'), '/* local webfonts (Cairo + Amiri) — generated by tools/fetch-fonts.mjs */\n' + localCss);
console.log(`DONE fonts ok=${ok} fail=${fail}`);